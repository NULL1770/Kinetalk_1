"""Evaluate emotion and style semantics of the deployed Stage-4 generator.

This is an internal semantic-consistency diagnostic.  The frozen Stage-2
emotion encoder judges the residual generated by the actual Stage-4 deployment
path.  It therefore measures whether Stage 4 preserves the factor coordinate
used during training, not independent human-perceived emotion recognition.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from kinetalk_b0.data import B0ResidualDataset, collate_b0_residual
from kinetalk_b0.models import Stage1Model, Stage2Model, Stage3Model, Stage4Model
from kinetalk_b0.utils import load_checkpoint, load_yaml, move_to_device, seed_everything


def file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_stage4(cfg: dict[str, Any], device: torch.device) -> tuple[Stage4Model, dict[str, Any]]:
    metadata: dict[str, Any] = {}

    def load(name: str, model: torch.nn.Module) -> None:
        path = Path(cfg["paths"][f"{name}_ckpt"])
        payload = load_checkpoint(path, model, map_location="cpu", strict=True)
        bad = [key for key, value in model.state_dict().items() if value.is_floating_point() and not torch.isfinite(value).all()]
        if bad:
            raise RuntimeError(f"{name} checkpoint has non-finite tensors: {bad[:3]}")
        metadata[name] = {
            "path": str(path.resolve()),
            "sha256": file_hash(path),
            "epoch": payload.get("epoch"),
            "strict_load": True,
        }

    stage1 = Stage1Model(cfg)
    load("stage1", stage1)
    stage2 = Stage2Model(cfg)
    load("stage2", stage2)
    stage3 = Stage3Model(cfg, stage2)
    load("stage3", stage3)
    stage4 = Stage4Model(cfg, stage1, stage2, stage3)
    load("stage4", stage4)
    return stage4.to(device).eval(), metadata


def masked_mae(left: torch.Tensor, right: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
    weight = mask.to(left.dtype).unsqueeze(-1).expand_as(left)
    return (left - right).abs().mul(weight).sum() / weight.sum().clamp_min(1)


def masked_velocity_correlation(left: torch.Tensor, right: torch.Tensor, mask: torch.Tensor, channels: torch.Tensor) -> torch.Tensor:
    if left.shape[1] < 2:
        return left.new_zeros(())
    valid = (mask[:, 1:] & mask[:, :-1]).to(left.dtype).unsqueeze(-1)
    a = (left[:, 1:] - left[:, :-1])[..., channels]
    b = (right[:, 1:] - right[:, :-1])[..., channels]
    count = valid.sum(dim=1, keepdim=True).clamp_min(1)
    a = (a - (a * valid).sum(dim=1, keepdim=True) / count) * valid
    b = (b - (b * valid).sum(dim=1, keepdim=True) / count) * valid
    numerator = (a * b).sum(dim=1)
    denominator = (a.square().sum(dim=1).sqrt() * b.square().sum(dim=1).sqrt()).clamp_min(1e-8)
    return (numerator / denominator).mean()


def classification(target: torch.Tensor, prediction: torch.Tensor, names: list[str]) -> dict[str, Any]:
    n_classes = len(names)
    confusion = torch.bincount(target * n_classes + prediction, minlength=n_classes * n_classes).view(n_classes, n_classes)
    support = confusion.sum(1)
    present = support > 0
    recall = confusion.diag().double() / support.clamp_min(1)
    return {
        "n": int(support.sum()),
        "accuracy": float(confusion.diag().sum() / support.sum().clamp_min(1)),
        "balanced_accuracy": float(recall[present].mean()) if present.any() else None,
        "class_order": names,
        "confusion_orientation": "rows=true, columns=predicted",
        "confusion": confusion.tolist(),
        "per_class_recall": {name: float(recall[index]) if present[index] else None for index, name in enumerate(names)},
        "class_counts": {name: int(support[index]) for index, name in enumerate(names)},
    }


def append(store: dict[str, list[torch.Tensor]], name: str, value: torch.Tensor) -> None:
    store.setdefault(name, []).append(value.detach().float().cpu().reshape(-1))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=Path("configs/train.yaml"))
    parser.add_argument("--split", choices=("train", "val", "test"), default="val",
                        help="Manifest split; validation is the default and test is for final frozen evaluation")
    parser.add_argument("--per-emotion", type=int, default=0, help="0 evaluates every accepted example")
    parser.add_argument("--steps", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.per_emotion < 0 or args.steps < 1 or args.batch_size < 1 or args.workers < 0:
        parser.error("per-emotion/workers must be nonnegative and steps/batch-size must be positive")

    cfg = load_yaml(args.config)
    seed_everything(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dataset = B0ResidualDataset(cfg, split=args.split, random_crop=False)
    names = list(dataset.emotion_classes)
    selected: list[int] = []
    for label, name in enumerate(names):
        indices = [index for index, item in enumerate(dataset.items) if dataset._emotion_name(item) == name]
        if args.per_emotion:
            generator = torch.Generator().manual_seed(args.seed + label)
            order = torch.randperm(len(indices), generator=generator).tolist()
            indices = [indices[index] for index in order[:args.per_emotion]]
        selected.extend(indices)
    selected = sorted(selected)
    if not selected:
        raise RuntimeError("No examples selected")
    loader = DataLoader(
        torch.utils.data.Subset(dataset, selected), batch_size=args.batch_size, shuffle=False,
        num_workers=args.workers, pin_memory=device.type == "cuda", persistent_workers=args.workers > 0,
        collate_fn=collate_b0_residual,
    )
    model, checkpoints = load_stage4(cfg, device)
    mouth = torch.zeros(int(cfg["data"]["motion_dim"]), dtype=torch.bool, device=device)
    mouth[list(cfg["data"]["neutral_output_indices"])] = True
    prediction, target, audio_prediction, intensity_prediction, intensity_target = [], [], [], [], []
    per_emotion: dict[str, dict[str, list[torch.Tensor]]] = defaultdict(dict)
    scalars: dict[str, list[torch.Tensor]] = {}
    pair_counts: Counter[str] = Counter()

    with torch.inference_mode():
        for batch_number, cpu_batch in enumerate(loader, start=1):
            batch = move_to_device(cpu_batch, device)
            query, reference = batch["query"], batch["style_reference"]
            conditions = model.conditions(batch)
            final, generated_residual = model.render(batch, conditions, steps=args.steps, stochastic=False)
            # Evaluate generated residual in the same predicted-B0 coordinate as
            # deployment.  The reference output is the real query motion in that
            # coordinate; it is not the ground-truth-neutral Stage-2 teacher.
            target_residual = query["motion"] - conditions["b0_pred"]
            generated_factors = model.factor_emotion(generated_residual, query["mask"])
            target_factors = model.factor_emotion(target_residual, query["mask"])
            audio_factors = model.audio_prior(query["audio_emotion"], query["mask"])
            reencoded_style = model.factor_style(generated_residual, query["mask"], query["audio_emotion"])

            prediction.append(generated_factors["emotion_logits"].argmax(-1).cpu())
            target.append(query["emotion_id"].cpu())
            audio_prediction.append(audio_factors["emotion_logits"].argmax(-1).cpu())
            intensity_prediction.append(generated_factors["intensity_logits"].argmax(-1).cpu())
            intensity_target.append(query["intensity_id"].cpu())
            append(scalars, "generator_emotion_agrees_with_target_residual", (generated_factors["emotion_logits"].argmax(-1) == target_factors["emotion_logits"].argmax(-1)).float())
            append(scalars, "generator_emotion_global_cosine_to_target_residual", F.cosine_similarity(generated_factors["global"], target_factors["global"], dim=-1))
            append(scalars, "audio_global_cosine_to_generated_residual", F.cosine_similarity(audio_factors["global"], generated_factors["global"], dim=-1))
            append(scalars, "style_condition_recovery_cosine", F.cosine_similarity(reencoded_style, conditions["style"], dim=-1))

            # Swap complete style codes across queries. Query audio/content stay
            # fixed, so output motion difference measures the active style path.
            if query["motion"].shape[0] > 1:
                alternate = dict(conditions)
                alternate["style"] = torch.roll(conditions["style"], shifts=1, dims=0)
                alternate_final, _ = model.render(batch, alternate, steps=args.steps, stochastic=False)
                append(scalars, "style_swap_delta_all52", masked_mae(final, alternate_final, query["mask"]))
                append(scalars, "style_swap_delta_mouth", masked_mae(final[..., mouth], alternate_final[..., mouth], query["mask"]))
                append(scalars, "style_swap_mouth_velocity_correlation", masked_velocity_correlation(final, alternate_final, query["mask"], mouth))

            for row, label in enumerate(query["emotion_id"].tolist()):
                name = names[int(label)]
                local = per_emotion[name]
                append(local, "generated_emotion_correct", generated_factors["emotion_logits"][row].argmax().eq(query["emotion_id"][row]).float())
                append(local, "generated_intensity_correct", generated_factors["intensity_logits"][row].argmax().eq(query["intensity_id"][row]).float())
                append(local, "style_recovery_cosine", F.cosine_similarity(reencoded_style[row:row + 1], conditions["style"][row:row + 1], dim=-1))
                pair_counts[f"reference_same_speaker={bool(reference['speaker'][row] == query['speaker'][row])}"] += 1
            if batch_number % 20 == 0 or batch_number == len(loader):
                print(f"batches={batch_number}/{len(loader)} samples={len(target) * args.batch_size}", flush=True)

    target_tensor = torch.cat(target)
    generated_prediction = torch.cat(prediction)
    audio_prediction_tensor = torch.cat(audio_prediction)
    intensity_target_tensor = torch.cat(intensity_target)
    intensity_prediction_tensor = torch.cat(intensity_prediction)
    result = {
        "schema_version": 1,
        "evaluation_mode": "deployment_semantic_consistency",
        "independent_motion_recognizer": False,
        "generator_heldout_generalization_established": False,
        "split": args.split,
        "selected_samples": int(target_tensor.numel()),
        "checkpoints": checkpoints,
        "protocol": {
            "generator": "Stage4.conditions plus deterministic Stage4.render, with different reference samples supplied by B0ResidualDataset",
            "emotion_metric": "Frozen Stage4-embedded Stage2 residual emotion classifier on generated residual = final - predicted_B0",
            "style_metric": "Frozen Stage4 style encoder re-encodes the generated residual; cosine is compared with the exact style condition consumed by the renderer",
            "style_intervention": "Within-batch cyclic replacement of complete style code while preserving each query's audio/content/global condition",
            "caveat": "This is not an independent emotion-recognition model, a speaker-style classifier, or a human perceptual study. It tests internal factor/renderer consistency only.",
        },
        "emotion": {
            "generated_residual_vs_target_label": classification(target_tensor, generated_prediction, names),
            "audio_prior_vs_target_label": classification(target_tensor, audio_prediction_tensor, names),
        },
        "intensity": {
            "generated_residual_vs_target_label": classification(intensity_target_tensor, intensity_prediction_tensor, [str(i) for i in range(int(cfg["data"]["num_intensity_levels"]))]),
        },
        "aggregate": {name: float(torch.cat(values).mean()) for name, values in sorted(scalars.items())},
        "per_emotion": {
            name: {metric: float(torch.cat(values).mean()) for metric, values in sorted(metrics.items())}
            for name, metrics in per_emotion.items()
        },
        "reference_pair_counts": dict(pair_counts),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False), encoding="utf-8")
    print(json.dumps({
        "output": str(args.output.resolve()),
        "emotion_accuracy": result["emotion"]["generated_residual_vs_target_label"]["accuracy"],
        "emotion_balanced_accuracy": result["emotion"]["generated_residual_vs_target_label"]["balanced_accuracy"],
        "style_recovery_cosine": result["aggregate"]["style_condition_recovery_cosine"],
    }), flush=True)


if __name__ == "__main__":
    main()
